        foreach (var (name, expected) in Evidence.Where(e => IsCurrency(e.Name) == currency))
        {
            vfp.Execute(Scenario(name));
            string actual = vfp.Memory.Get("result").AsString;
            if (actual != expected) failures.Add($"{name}: expected [{expected}], actual [{actual}]");
        }
        Assert.True(failures.Count == 0, string.Join("\n", failures));
    }
