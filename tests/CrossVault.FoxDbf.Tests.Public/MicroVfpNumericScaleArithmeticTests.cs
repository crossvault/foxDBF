    internal static string Scenario(string name)
    {
        int colon = name.IndexOf(':');
        string expression = name[(colon + 1)..];
        if (name.StartsWith("changed:"))
            return "SET DECIMALS TO 2\nx=" + expression + "\nSET DECIMALS TO 4\ny=x+1\nresult=TRANSFORM(x)+'|'+TRANSFORM(y)+'|'+STR(x)+'|'+STR(y)";
        return $"SET DECIMALS TO {name[1]}\nx={expression}\nresult=TRANSFORM(x)+'|'+STR(x)+'|'+TRANSFORM(LEN(TRANSFORM(x)))+'|'+TYPE('x')+'|'+STR(x,30,10)";
    }
