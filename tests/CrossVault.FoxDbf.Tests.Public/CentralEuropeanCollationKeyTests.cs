    {
        byte mark = codePage switch { 1250 => 0xC8, 852 => 0x64, 895 => 0x68, 620 => 0x69, _ => throw new ArgumentOutOfRangeException(nameof(codePage)) };
        string value = Encodings.ResolveEncoding(mark).GetString(Convert.FromHexString(inputHex));
        Assert.Equal(expected, Convert.ToHexString(VfpCollations.ByName(name, codePage).GetCollatedKey(value)));
    }
