        Assert.Equal(key, Convert.ToHexString(collation.GetCollatedKey(value)));
        var context = new EvaluationContext { Encoding = encoding };
        string up = VfpRuntime.CallFunction("UPPER", [VfpValue.Character(value)], context, null!).AsString;
        string lo = VfpRuntime.CallFunction("LOWER", [VfpValue.Character(value)], context, null!).AsString;
        Assert.Equal(upper, Convert.ToHexString(collation.GetCollatedKey(up)));
        Assert.Equal(lower, Convert.ToHexString(collation.GetCollatedKey(lo)));
    }
