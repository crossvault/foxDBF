    [Theory]
    [InlineData("n45 > 3 AND n45 < 10", "n45>3.AND.n45<10")]
    [InlineData("n45 > 0 AND .T.", "n45>0.AND..T.")]
    [InlineData("n45 >= 5", "n45=>5")]
    [InlineData("n45 =< 5", "n45<=5")]
    [InlineData("n45 % 3 % 2 = 0", "MOD(MOD(n45,3),2)=0")]
    [InlineData("n45 = 0x5", "n45=5")]
    [InlineData("t->name = 'ab'", "T.name=\"ab\"")]
    [InlineData("n45 ^ 2 > 24", "n45**2>24")]
    [InlineData("NOT lg OR !EMPTY(name)", ".NOT.lg.OR..NOT.EMPTY(name)")]
    [InlineData("SUBSTR(name, 1, 1) = 'a'", "SUBSTR(name,1,1)=\"a\"")]
    [InlineData("n45 * (2 + 3) = 25", "n45*5=25")]
    [InlineData("n45 = 5.0", "n45=5.0")]
    public void StoredText_ParsesAndMeansWhatWasTyped(string typed, string stored)
    {
        var row = new TestRow().Set("n45", 5m).Set("name", "ab").Set("lg", false).Set("T.name", "ab");
        Assert.Equal(stored, VfpExpressionText.Canonicalize(typed));
        Assert.Equal(Ev.Eval(typed, row), Ev.Eval(stored, row));
        Assert.Equal(stored, VfpExpressionText.Canonicalize(stored));   // a fixed point: REINDEX keeps it
    }

    [Fact]
    public void Lexer_ReadsTheCurrencyLiteralVfpStores()
    {
        Assert.Equal(VfpType.Currency, Ev.Eval("$12.5000").Type);
        Assert.Equal(12.5m, Ev.Eval("$12.5000").AsNumber);
        Assert.True(Ev.Eval("\"a\"$\"abc\"").AsLogical);              // after an operand '$' stays the operator
    }
